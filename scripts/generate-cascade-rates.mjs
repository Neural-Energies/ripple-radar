/**
 * Turn the conflict-cascade run into a typed module the app can import.
 *
 * Generated, never hand-edited: these are the output of a Hawkes fit with a
 * chronological holdout, and a human editing them puts the product back to the
 * authored-constant problem the rest of this work removed.
 *
 * Only countries that cleared the gate are emitted. A country that failed, or
 * was never fitted, is absent — the app renders absence, not a default.
 */
import { readFileSync, writeFileSync } from "node:fs";

const IN = process.argv[2] ?? "artifacts/reports/ace_gdelt_cascade_v1_scorecard.json";
const OUT = process.argv[3] ?? "src/lib/ace/cascade-rates.ts";

const art = JSON.parse(readFileSync(IN, "utf8"));
const passing = (art.countries ?? []).filter((c) => !c.skipped && c.passes);
if (!passing.length) {
  console.error("generate-cascade-rates: no country cleared the gate — refusing to emit");
  process.exit(1);
}

const rows = passing
  .sort((a, b) => b.oos_gain - a.oos_gain)
  .map((c) => {
    const f = c.fit;
    const k = c.cascade ?? {};
    return `  ${JSON.stringify(c.code)}: {
    code: ${JSON.stringify(c.code)},
    name: ${JSON.stringify(c.name)},
    spikeDays: ${c.n_events},
    branchingRatio: ${f.alpha},
    excitationHalfLifeDays: ${k.excitation_half_life ?? null},
    cascadeMultiplier: ${k.cascade_multiplier ?? null},
    directOffspringWithinHorizon: ${k.direct_offspring_within_horizon ?? null},
    lrPValue: ${f.lr_p_value},
    oosGainOverPoisson: ${c.oos_gain},
    firstEvent: ${JSON.stringify(c.first_event)},
    lastEvent: ${JSON.stringify(c.last_event)},
    meanEventsPerDay: ${c.mean_per_day},
  },`;
  })
  .join("\n");

const spec = art.pooled_specification ?? {};
const grid = art.discretization ?? {};

const file = `// GENERATED by scripts/generate-cascade-rates.mjs — do not edit by hand.
// Source: ${IN}
//
// Measured self-excitation in material conflict events (GDELT, CAMEO quad
// class 4), by the country the action occurred in.
//
// Only countries that cleared the gate appear. A country that failed, or was
// never fitted, is ABSENT — the app must render that absence rather than fall
// back to a default.
//
// WHAT IS ESTABLISHED: escalation clusters. The likelihood-ratio test against a
// homogeneous Poisson process clears p = ${art.countries?.filter((c) => c.passes).reduce((m, c) => Math.max(m, c.fit.lr_p_value), 0) ?? "?"} on every country here, and
// every one gains out of sample under parameters fitted before the holdout.
//
// WHAT IS NOT: the intensity's exact shape. Pooled Ogata residuals reject a
// CONTINUOUS Exp(1) null — but these events sit on a daily grid where 47% of
// gaps are exactly one day, and a continuous null rejects gridded data for that
// reason alone. Correcting for the floor does not restore the fit either, so
// discretization and kernel shape are confounded and neither is established.
//
// Consequence for display: the branching ratio is an ORDER-OF-MAGNITUDE
// statement about how much one escalation breeds. It is not a three-digit
// estimate and must not be rendered as one.

export interface CascadeRate {
  /** FIPS 10-4 country code, as GDELT emits it. */
  code: string;
  name: string;
  /** Spike days the fit was built from. */
  spikeDays: number;
  /**
   * Expected direct offspring per event. Below 1 the process is stationary —
   * escalations amplify and die out rather than running away.
   */
  branchingRatio: number;
  /** How fast the excitation decays. Near one day across the board. */
  excitationHalfLifeDays: number | null;
  /** Total events per independent event, across all generations. */
  cascadeMultiplier: number | null;
  directOffspringWithinHorizon: number | null;
  /** Likelihood-ratio p against a homogeneous Poisson process. */
  lrPValue: number;
  /** Out-of-sample log-likelihood gain over Poisson. */
  oosGainOverPoisson: number;
  firstEvent: string;
  lastEvent: string;
  meanEventsPerDay: number;
}

export const CASCADE_RATES: Record<string, CascadeRate> = {
${rows}
};

export const CASCADE_RUN = {
  nMaterialEvents: ${art.n_material ?? 0},
  sigma: ${art.sigma},
  windowDays: ${art.window},
  testFraction: ${art.test_frac},
  nFitted: ${art.n_fitted ?? 0},
  nPassing: ${art.n_passing ?? 0},
  selection: ${JSON.stringify(art.selection ?? {})},
  specification: {
    trainKsP: ${spec.train?.ks_p_value ?? null},
    holdoutKsP: ${spec.holdout?.ks_p_value ?? null},
    residualFloor: ${grid.residual_floor ?? null},
    massUnreachableOnDailyGrid: ${grid.mass_unreachable_on_a_daily_grid ?? null},
    conditionalKsP: ${grid.conditional_ks_p ?? null},
    note:
      "Pooled Ogata residuals reject a continuous Exp(1) null, but these events " +
      "sit on a daily grid where no two can be closer than one day. Discretization " +
      "and kernel shape are confounded; neither is established. Treat the " +
      "branching ratio as approximate.",
  },
} as const;

export function cascadeFor(code: string): CascadeRate | undefined {
  return CASCADE_RATES[code.toUpperCase()];
}

/** Every measured cascade, strongest out-of-sample evidence first. */
export function allCascades(): CascadeRate[] {
  return Object.values(CASCADE_RATES).sort((a, b) => b.oosGainOverPoisson - a.oosGainOverPoisson);
}
`;

writeFileSync(OUT, file);
console.log(`generated ${OUT} — ${passing.length} countries cleared the gate`);
