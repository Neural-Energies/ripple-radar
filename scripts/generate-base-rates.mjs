/**
 * Turn the validated competing-risks run into a typed base-rate table.
 *
 * Generated, not hand-written: these numbers are the output of an executed
 * Aalen-Johansen fit on 4,633 shocks with a sealed holdout, and a human
 * editing them would put the product straight back to the authored-constant
 * problem this replaces.
 */
import { readFileSync, writeFileSync } from "node:fs";

const IN = process.argv[2] ?? "artifacts/reports/ace_competing_risks_v1_scorecard.json";
const OUT = process.argv[3] ?? "src/lib/ace/base-rates.ts";

const art = JSON.parse(readFileSync(IN, "utf8"));
if (!art.passes) {
  console.error("generate-base-rates: the competing-risks model did not pass its gate — refusing");
  process.exit(1);
}
const cif = art.cif;
const grid = cif.horizon_grid ?? [];
const esc = cif.cif?.escalation ?? [];
const cont = cif.cif?.continuation ?? [];
if (!grid.length || grid.length !== esc.length || grid.length !== cont.length) {
  console.error("generate-base-rates: malformed CIF arrays");
  process.exit(1);
}

// One row per grid point: cumulative incidence of each competing cause, plus
// the residual (neither has happened yet by this horizon).
const rows = grid
  .map((d, i) => {
    const e = Number(esc[i]);
    const c = Number(cont[i]);
    const r = 1 - e - c;
    if (!(e >= 0 && c >= 0 && r >= -1e-9)) {
      console.error(`generate-base-rates: incoherent row at horizon ${d}`);
      process.exit(1);
    }
    return `  { days: ${Number(d)}, escalation: ${e}, continuation: ${c}, neither: ${Math.max(0, r)} },`;
  })
  .join("\n");

const calib = (art.calibration ?? [])
  .map(
    (r) =>
      `  { days: ${r.horizon}, cause: ${JSON.stringify(r.cause)}, predicted: ${r.predicted}, realized: ${r.realized}, error: ${r.error}, n: ${r.n} },`,
  )
  .join("\n");

const file = `// GENERATED by scripts/generate-base-rates.mjs — do not edit by hand.
// Source: ${IN}
//
// Empirical base rates for "after a shock, what happens next", from an
// Aalen-Johansen competing-risks fit.
//
//   subjects (train)     ${cif.n_subjects}
//   total mainshocks     ${art.n_mainshocks}
//   sealed holdout       ${art.n_test}
//   censored             ${cif.n_censored}
//   worst holdout error  ${art.worst_error}
//   naive KM baseline    ${Number(art.baseline_worst_error).toFixed(4)}
//
// Competing risks, not independent survival: escalation and continuation
// FORECLOSE each other, and the naive Kaplan-Meier treatment that censors the
// competing cause is wrong by 28.8 points at worst against 3.5 for this fit.
//
// REFERENCE CLASS, stated plainly: these rates were measured on MARKET shocks
// (|return| >= 2 sigma), not on news events. Using them as a prior for a news
// book is a reference-class transfer. It is a far better starting point than an
// authored constant, and it is not the same population — any consumer must
// surface that, which is why \`BASE_RATE_REFERENCE_CLASS\` exists and is shown.

export interface BaseRateRow {
  /** Horizon in days since the shock. */
  days: number;
  /** Cumulative incidence of escalation by this horizon. */
  escalation: number;
  /** Cumulative incidence of continuation-without-escalation. */
  continuation: number;
  /** Residual: neither has occurred by this horizon. */
  neither: number;
}

export const SHOCK_BASE_RATES: BaseRateRow[] = [
${rows}
];

/** Out-of-sample calibration of the curves above, on the sealed holdout. */
export const BASE_RATE_CALIBRATION = [
${calib}
] as const;

export const BASE_RATE_PROVENANCE = {
  model: "aalen_johansen_competing_risks",
  modelId: "ace_competing_risks",
  version: "v1",
  nSubjects: ${cif.n_subjects},
  nHoldout: ${art.n_test},
  worstHoldoutError: ${art.worst_error},
  naiveBaselineWorstError: ${Number(art.baseline_worst_error)},
  causes: ${JSON.stringify(cif.causes ?? [])},
} as const;

export const BASE_RATE_REFERENCE_CLASS =
  "Measured on market shocks (|return| >= 2 sigma), not on news events. " +
  "Applying it to a news book is a reference-class transfer.";

/**
 * Cumulative incidence at an arbitrary horizon, linearly interpolated.
 *
 * A step function evaluated between its knots would jump; the curve is
 * monotone and smooth enough between grid points that interpolating is the
 * honest read. Outside the grid it clamps to the nearest end rather than
 * extrapolating a survival curve it never measured.
 */
export function baseRateAt(days: number): BaseRateRow {
  const g = SHOCK_BASE_RATES;
  if (!g.length) throw new Error("base rates are empty");
  if (days <= g[0]!.days) return g[0]!;
  const last = g[g.length - 1]!;
  if (days >= last.days) return last;
  for (let i = 1; i < g.length; i++) {
    const a = g[i - 1]!;
    const b = g[i]!;
    if (days <= b.days) {
      const t = (days - a.days) / (b.days - a.days || 1);
      const mix = (x: number, y: number) => x + (y - x) * t;
      return {
        days,
        escalation: mix(a.escalation, b.escalation),
        continuation: mix(a.continuation, b.continuation),
        neither: mix(a.neither, b.neither),
      };
    }
  }
  return last;
}
`;

writeFileSync(OUT, file);
console.log(
  `generated ${OUT} — ${grid.length} horizons, ${cif.n_subjects} subjects, worst holdout error ${art.worst_error}`,
);
