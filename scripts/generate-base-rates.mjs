/**
 * Turn the validated competing-risks run into a typed base-rate table.
 *
 * Generated, not hand-written: these numbers are the output of an executed
 * Aalen-Johansen fit with a sealed holdout, and a human editing them would put
 * the product straight back to the authored-constant problem this replaces.
 * The population and baseline are read from the scorecard, not written here:
 * an earlier hand-written header called 4,633 earthquake mainshocks "market
 * shocks" and a marginal-share baseline "naive Kaplan-Meier".
 */
import { readFileSync, writeFileSync } from "node:fs";

const IN = process.argv[2] ?? "artifacts/reports/ace_competing_risks_v2_scorecard.json";
const OUT = process.argv[3] ?? "src/lib/ace/base-rates.ts";

const art = JSON.parse(readFileSync(IN, "utf8"));
if (!art.passes) {
  console.error("generate-base-rates: the competing-risks model did not pass its gate — refusing");
  process.exit(1);
}
if (!art.population || !art.baseline) {
  console.error("generate-base-rates: scorecard does not state its population and baseline — refusing");
  process.exit(1);
}
const cif = art.cif;
const grid = cif.horizon_grid ?? [];
const esc = cif.cif?.escalation ?? [];
const cont = cif.cif?.continuation ?? [];
if (!grid.length || grid.length !== esc.length || grid.length !== cont.length || grid[0] !== 0) {
  console.error("generate-base-rates: malformed CIF arrays");
  process.exit(1);
}
for (let i = 0; i < grid.length; i++) {
  const e = Number(esc[i]);
  const c = Number(cont[i]);
  if (!(e >= 0 && c >= 0 && 1 - e - c >= -1e-6) || (i > 0 && !(grid[i] > grid[i - 1]))) {
    console.error(`generate-base-rates: incoherent row at horizon ${grid[i]}`);
    process.exit(1);
  }
}

const scored = (art.calibration ?? []).filter((r) => r.supported);
const calib = scored
  .map(
    (r) =>
      `  { days: ${r.horizon}, cause: ${JSON.stringify(r.cause)}, predicted: ${r.predicted}, realized: ${r.realized}, realizedCi: [${r.realized_ci.join(", ")}], error: ${r.error}, atRisk: ${r.n_at_risk} },`,
  )
  .join("\n");

const version = IN.match(/_(v\d+)_scorecard\.json$/)?.[1] ?? "unknown";
const arr = (xs) => `[${xs.map(Number).join(",")}]`;

const file = `// GENERATED by scripts/generate-base-rates.mjs — do not edit by hand.
// Source: ${IN}
//
// Empirical base rates for "after a shock, what happens next", from an
// Aalen-Johansen competing-risks fit.
//
//   population           ${art.population}
//   subjects (train)     ${cif.n_subjects}
//   total                ${art.n_mainshocks}
//   sealed holdout       ${art.n_test}
//   censored (train)     ${cif.n_censored}
//   worst holdout error  ${Number(art.worst_error).toFixed(4)}
//   baseline             ${art.baseline}, worst error ${Number(art.baseline_worst_error).toFixed(4)}
//
// The holdout is scored against its OWN censor-aware Aalen-Johansen incidence,
// only at horizons it was followed to with enough subjects still at risk.
//
// The curve is a STEP FUNCTION: incidence only moves when an event happens.
// Every jump of the fit is kept (${grid.length} of them), so a lookup at any
// horizon returns exactly what the fit says there — nothing is interpolated.

export interface BaseRateRow {
  /** Horizon in days since the shock. */
  days: number;
  /** Cumulative incidence of escalation by this horizon. */
  escalation: number;
  /** Cumulative incidence of continuation-without-escalation. */
  continuation: number;
  /** Residual: neither has occurred by this horizon. */
  neither: number;
}

const DAYS = ${arr(grid)};
const ESCALATION = ${arr(esc)};
const CONTINUATION = ${arr(cont)};

/** One row per jump of the fitted curve, led by a zero row at day 0. */
export const SHOCK_BASE_RATES: BaseRateRow[] = DAYS.map((days, i) => {
  const escalation = ESCALATION[i]!;
  const continuation = CONTINUATION[i]!;
  return { days, escalation, continuation, neither: Math.max(0, 1 - escalation - continuation) };
});

/** Out-of-sample calibration of the curves above, on the sealed holdout. */
export const BASE_RATE_CALIBRATION = [
${calib}
] as const;

export const BASE_RATE_PROVENANCE = {
  model: "aalen_johansen_competing_risks",
  modelId: "ace_competing_risks",
  version: ${JSON.stringify(version)},
  nSubjects: ${cif.n_subjects},
  nHoldout: ${art.n_test},
  worstHoldoutError: ${art.worst_error},
  naiveBaselineWorstError: ${Number(art.baseline_worst_error)},
  maxFollowUpDays: ${cif.max_follow_up},
  causes: ${JSON.stringify(cif.causes ?? [])},
} as const;

export const BASE_RATE_REFERENCE_CLASS =
  ${JSON.stringify(`Measured on ${art.population}. Not market shocks and not news events: applying it to a news book is a cross-domain reference-class transfer.`)};

/**
 * Cumulative incidence at a horizon: the value at the last jump at or before
 * it. Before day 0 that is the zero row; past the last jump the curve is flat
 * to the end of follow-up (${cif.max_follow_up} days), which is where the
 * causes stop being counted.
 */
export function baseRateAt(days: number): BaseRateRow {
  const g = SHOCK_BASE_RATES;
  if (!g.length) throw new Error("base rates are empty");
  let lo = 0;
  let hi = g.length - 1;
  if (!(days >= g[0]!.days)) return g[0]!;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (g[mid]!.days <= days) lo = mid;
    else hi = mid - 1;
  }
  return g[lo]!;
}
`;

writeFileSync(OUT, file);
console.log(
  `generated ${OUT} — ${grid.length} jumps, ${cif.n_subjects} subjects, worst holdout error ${art.worst_error}`,
);
