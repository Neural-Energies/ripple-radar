/**
 * Turn the measured-edge artifact into a typed module the app can import.
 *
 * Generated rather than hand-maintained: the whole point is that these numbers
 * come from a measurement run and not from an author's judgement, so a human
 * editing this file would defeat the exercise. Re-run the calibrator and
 * regenerate.
 */
import { readFileSync, writeFileSync } from "node:fs";

const IN = process.argv[2] ?? "artifacts/reports/transmission_edges.json";
const OUT = process.argv[3] ?? "src/lib/engine/transmission-evidence.ts";

const art = JSON.parse(readFileSync(IN, "utf8"));
const edges = art.edges ?? [];
if (!edges.length) {
  console.error("generate-transmission-evidence: artifact has no edges");
  process.exit(1);
}

const num = (v) => (v === null || v === undefined || Number.isNaN(v) ? "null" : String(v));
const str = (v) => JSON.stringify(v ?? "");

const rows = edges
  .map((e) => {
    const key = `${e.from_tag}|${e.to_tag}`;
    return `  ${JSON.stringify(key)}: {
    status: ${str(e.status)},
    fromProxy: ${e.from_proxy ? str(e.from_proxy) : "null"},
    toProxy: ${e.to_proxy ? str(e.to_proxy) : "null"},
    coupling: ${num(e.coupling)},
    signStability: ${num(e.sign_stability)},
    measuredDirection: ${num(e.measured_direction)},
    directionAgrees: ${e.direction_agrees === null || e.direction_agrees === undefined ? "null" : String(e.direction_agrees)},
    laggedHorizons: ${e.lagged_horizons ? JSON.stringify(e.lagged_horizons) : "null"},
    constructionOverlap: ${Boolean(e.construction_overlap)},
    nTrain: ${num(e.n_train)},
    nHoldout: ${num(e.n_holdout)},
    assertedConfidence: ${num(e.asserted_confidence)},
    note: ${str(e.note)},
  },`;
  })
  .join("\n");

const summary = Object.entries(art.summary ?? {})
  .sort((a, b) => b[1] - a[1])
  .map(([k, v]) => `//   ${k.padEnd(22)} ${v}`)
  .join("\n");

const file = `// GENERATED by scripts/generate-transmission-evidence.mjs — do not edit by hand.
// Source artifact: ${IN}
// Generated at: ${art.generated_at ?? "unknown"}
//
// Measured support for the Ripple graph's asserted transmission edges.
//
// ${art.confidence_definition ?? ""}
//
// Run summary:
${summary}
//
// \`signStability\` is NOT a strength. It answers "if I rely on this arrow, how
// often does it point the way the graph says?" — a weak relationship can have a
// perfectly stable sign. \`coupling\` (holdout |correlation|) carries the
// strength, and both must be shown together or the pair is misleading.

/** How much support the data gives an asserted edge. */
export type EdgeStatus =
  /** Both ends have a daily proxy and the holdout coupling clears the floor. */
  | "measured"
  /** Proxies exist; the relationship is indistinguishable from zero. */
  | "no_material_coupling"
  /** At least one end has no daily market proxy. Ontology, not measurement. */
  | "unmeasured"
  /** Both ends proxy to the SAME series — the edge restates one series against itself. */
  | "degenerate";

export interface EdgeEvidence {
  status: EdgeStatus;
  fromProxy: string | null;
  toProxy: string | null;
  /** Holdout |correlation|. The strength. Null unless measured. */
  coupling: number | null;
  /** Fraction of holdout bootstrap resamples keeping the training sign. */
  signStability: number | null;
  measuredDirection: number | null;
  /** False means the data contradicts the ontology's asserted direction. */
  directionAgrees: boolean | null;
  /** Lagged horizons surviving multiplicity correction. Empty everywhere so far. */
  laggedHorizons: number[] | null;
  /** The two proxies are not independent by construction (e.g. VIX and the S&P). */
  constructionOverlap: boolean;
  nTrain: number;
  nHoldout: number;
  /** What the ontology claimed before measurement, kept so the gap stays visible. */
  assertedConfidence: number;
  note: string;
}

export const TRANSMISSION_EVIDENCE: Record<string, EdgeEvidence> = {
${rows}
};

export const TRANSMISSION_RUN = {
  generatedAt: ${str(art.generated_at)},
  panelStart: ${str(art.panel_start)},
  holdoutFrac: ${num(art.holdout_frac)},
  couplingFloor: ${num(art.coupling_floor)},
  nBootstrap: ${num(art.n_bootstrap)},
  confidenceDefinition: ${str(art.confidence_definition)},
} as const;

export function edgeEvidence(from: string, to: string): EdgeEvidence | undefined {
  return TRANSMISSION_EVIDENCE[\`\${from}|\${to}\`];
}
`;

writeFileSync(OUT, file);
const counts = edges.reduce((a, e) => ({ ...a, [e.status]: (a[e.status] ?? 0) + 1 }), {});
console.log(`generated ${OUT} — ${edges.length} edges:`, counts);
