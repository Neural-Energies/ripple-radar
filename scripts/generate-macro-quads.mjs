/**
 * Turn the point-in-time quad run into a typed module the app can import.
 *
 * Generated, never hand-edited.
 *
 * The important behaviour here is what this generator REFUSES to emit. The
 * quad framework makes two separable claims:
 *
 *   1. The economy can be classified by the rate of change of growth and
 *      inflation, in real time, from data that had actually been published.
 *   2. Knowing which quad you are in tells you how to be positioned.
 *
 * Claim 1 held — 320 month-ends classified from ALFRED first-release vintages,
 * median 60 days behind the tape, with no revision ever leaking backwards.
 * Claim 2 failed the test in `ace/models/quad_model.py`: zero of six channels
 * beat simply being long the same asset out of sample, and only 11 of 23
 * usable quad cells kept their sign.
 *
 * So the emitted module carries the regime label and its lag, and sets
 * `POSITIONING_VALIDATED = false`. If a future run passes, the same generator
 * emits `true` and the app's gate opens on its own. Nobody hand-flips it.
 */
import { readFileSync, writeFileSync } from "node:fs";

const IN = process.argv[2] ?? "artifacts/reports/ace_macro_quad_v1_panel.json";
const OUT = process.argv[3] ?? "src/lib/ace/macro-quads.ts";

const art = JSON.parse(readFileSync(IN, "utf8"));

const current = art.current ?? {};
if (current.quad == null) {
  console.error("generate-macro-quads: the live reading is unclassified — refusing to emit");
  process.exit(1);
}
const history = (art.history ?? []).filter((r) => r.quad != null);
if (history.length < 12) {
  console.error(
    `generate-macro-quads: only ${history.length} classified months — refusing to emit`,
  );
  process.exit(1);
}

const validated = art.validation?.positioning_validated === true;

const num = (v) => (v == null || Number.isNaN(v) ? "null" : v);
const readingLiteral = (r, indent) => {
  const p = " ".repeat(indent);
  return `{
${p}  asOf: ${JSON.stringify(r.as_of)},
${p}  quad: ${r.quad},
${p}  name: ${JSON.stringify(r.name)},
${p}  description: ${JSON.stringify(r.reason ?? "")},
${p}  growthYoy: ${num(r.growth_yoy)},
${p}  inflationYoy: ${num(r.inflation_yoy)},
${p}  growthRoc: ${num(r.growth_roc)},
${p}  inflationRoc: ${num(r.inflation_roc)},
${p}  growthThrough: ${JSON.stringify(r.growth_through)},
${p}  inflationThrough: ${JSON.stringify(r.inflation_through)},
${p}  dataLagDays: ${num(r.data_lag_days)},
${p}}`;
};

const quadMeta = Object.entries(art.framework?.quads ?? {})
  .map(
    ([q, m]) =>
      `  ${q}: { name: ${JSON.stringify(m.name)}, description: ${JSON.stringify(m.description)} },`,
  )
  .join("\n");

const lags = Object.entries(art.publication_lags ?? {})
  .map(
    ([sid, l]) =>
      `  ${JSON.stringify(sid)}: { medianDays: ${l.median_days}, p90Days: ${l.p90_days} },`,
  )
  .join("\n");

const transitions = Object.entries(art.transitions ?? {})
  .map(([from, row]) => {
    const cells = Object.entries(row)
      .map(([to, p]) => `${to}: ${Number(p).toFixed(4)}`)
      .join(", ");
    return `  ${from}: { ${cells} },`;
  })
  .join("\n");

const edges = Object.entries(art.validation?.channel_edges ?? {})
  .map(
    ([ch, e]) =>
      `  ${JSON.stringify(ch)}: { edgePctPerMonth: ${num(e.edge_pct_per_month)}, edgeCi: [${num(
        e.edge_ci?.[0],
      )}, ${num(e.edge_ci?.[1])}], signsHeld: ${num(e.signs_held)}, usableCells: ${num(
        e.usable_cells,
      )}, holdoutMonths: ${num(e.holdout_months)} },`,
  )
  .join("\n");

const file = `// GENERATED by scripts/generate-macro-quads.mjs — do not edit by hand.
// Source: ${IN}
//
// The growth/inflation quad: classify the economy by the RATE OF CHANGE of
// growth and inflation rather than their level, into four regimes.
//
//                   inflation decelerating   inflation accelerating
//   growth accel          Quad 1                    Quad 2
//                       "Goldilocks"              "Reflation"
//   growth decel          Quad 4                    Quad 3
//                       "Deflation"              "Stagflation"
//
// WHAT IS ESTABLISHED: the classification, point-in-time. Every reading here
// was built from ALFRED first-release vintages filtered to what had actually
// been PUBLISHED by its own date. ${art.coverage?.n_classified} month-ends from
// ${art.coverage?.first} to ${art.coverage?.last}, median ${art.coverage?.median_data_lag_days} days behind the tape.
// Real GDP is deliberately excluded: a ~119-day publication lag means the print
// describes a quarter that ended four months ago.
//
// WHAT IS NOT: that the quad tells you how to be positioned. Tested against
// "always long the same asset" over a sealed chronological holdout:
// ${art.validation?.channels_beating_long_only?.length ?? 0}/${art.validation?.channels_tested?.length ?? 0} channels beat that baseline with a CI excluding zero, and
// ${art.validation?.sign_stability?.held ?? 0}/${art.validation?.sign_stability?.usable ?? 0} usable quad cells kept their sign out of sample. That is a coin
// flip. POSITIONING_VALIDATED is therefore false, and the UI must render this
// as an ENVIRONMENT LABEL with its lag stated — never as a trade.
//
// Consequence for display: show the quad, the rates of change behind it, and
// how far behind the data is. Do not rank assets by it.

export type Quad = 1 | 2 | 3 | 4;

export interface QuadReading {
  /** The date this classification was made FOR, not the date data was observed. */
  asOf: string;
  quad: Quad;
  name: string;
  description: string;
  /** Year-on-year rate of the composite, in percent. The LEVEL. */
  growthYoy: number | null;
  inflationYoy: number | null;
  /**
   * How that year-on-year rate compares with itself a quarter ago, in points.
   * This is the second derivative the framework turns on — and the reason a
   * quad can read "Goldilocks" while growth is still negative in level.
   */
  growthRoc: number | null;
  inflationRoc: number | null;
  /** Newest observation month each input had published by \`asOf\`. */
  growthThrough: string | null;
  inflationThrough: string | null;
  /** Days between the newest input observation and \`asOf\`. */
  dataLagDays: number | null;
}

export const QUADS: Record<number, { name: string; description: string }> = {
${quadMeta}
};

/** The live reading, from what was published when this module was generated. */
export const CURRENT_QUAD: QuadReading = ${readingLiteral(current, 0)};

/** Month-end readings, oldest first. Each uses only its own point-in-time data. */
export const QUAD_HISTORY: readonly QuadReading[] = [
${history.map((r) => "  " + readingLiteral(r, 2) + ",").join("\n")}
];

/**
 * Whether the POSITIONING claim cleared its gate. False here means the app
 * must not turn the quad into asset guidance. The generator writes this from
 * the validation run; it is not a hand-set flag.
 */
export const POSITIONING_VALIDATED = ${validated};

export const QUAD_RUN = {
  generatedAt: ${JSON.stringify(art.generated_at)},
  rocLookbackMonths: ${art.framework?.roc_lookback_months ?? null},
  growthSeries: ${JSON.stringify(art.framework?.growth_series ?? [])},
  inflationSeries: ${JSON.stringify(art.framework?.inflation_series ?? [])},
  gdpExcludedReason: ${JSON.stringify(art.framework?.gdp_excluded_reason ?? "")},
  nClassified: ${art.coverage?.n_classified ?? 0},
  first: ${JSON.stringify(art.coverage?.first ?? "")},
  last: ${JSON.stringify(art.coverage?.last ?? "")},
  medianDataLagDays: ${art.coverage?.median_data_lag_days ?? null},
  maxDataLagDays: ${art.coverage?.max_data_lag_days ?? null},
  distribution: ${JSON.stringify(art.coverage?.distribution ?? {})},
  validation: {
    baseline: ${JSON.stringify(art.validation?.baseline ?? "")},
    horizonMonths: ${art.validation?.horizon_months ?? null},
    channelsTested: ${JSON.stringify(art.validation?.channels_tested ?? [])} as readonly string[],
    // Annotated rather than inferred: when this is empty \`as const\` would give
    // it element type \`never\`, and every consumer that asks whether a channel
    // is in it would stop compiling the moment the list is empty — which is
    // precisely the state the gate exists to represent.
    channelsBeatingLongOnly: ${JSON.stringify(
      art.validation?.channels_beating_long_only ?? [],
    )} as readonly string[],
    signsHeld: ${art.validation?.sign_stability?.held ?? null},
    usableCells: ${art.validation?.sign_stability?.usable ?? null},
  },
} as const;

/** Median and 90th-percentile publication lag per input series, in days. */
export const PUBLICATION_LAGS: Record<string, { medianDays: number; p90Days: number }> = {
${lags}
};

/**
 * Empirical quad-to-quad transitions, run-collapsed so this counts REGIME
 * CHANGES rather than how long each regime happened to last.
 *
 * Descriptive. It says how the regime HAS moved, not how it will — the
 * positioning test above is what would have made it predictive, and it failed.
 */
export const QUAD_TRANSITIONS: Record<number, Record<number, number>> = {
${transitions}
};

/** Out-of-sample edge over always-long, per channel. All CIs include zero. */
export const QUAD_CHANNEL_EDGES: Record<
  string,
  {
    edgePctPerMonth: number | null;
    edgeCi: [number | null, number | null];
    signsHeld: number | null;
    usableCells: number | null;
    holdoutMonths: number | null;
  }
> = {
${edges}
};

/** Where the quad has historically gone next, most likely first. */
export function likelyNextQuads(from: Quad): { quad: Quad; p: number }[] {
  const row = QUAD_TRANSITIONS[from] ?? {};
  return Object.entries(row)
    .map(([q, p]) => ({ quad: Number(q) as Quad, p }))
    .filter((r) => r.p > 0)
    .sort((a, b) => b.p - a.p);
}

/** How stale the reading is, given a clock. Null when the reading has no lag. */
export function stalenessDays(reading: QuadReading, nowMs: number): number | null {
  if (reading.growthThrough == null && reading.inflationThrough == null) return null;
  const newest = Math.max(
    reading.growthThrough ? Date.parse(reading.growthThrough + "T00:00:00Z") : 0,
    reading.inflationThrough ? Date.parse(reading.inflationThrough + "T00:00:00Z") : 0,
  );
  if (!Number.isFinite(newest) || newest <= 0) return null;
  return Math.floor((nowMs - newest) / 86_400_000);
}
`;

writeFileSync(OUT, file);
console.log(
  `generated ${OUT} — Q${current.quad} ${current.name} as of ${current.as_of}, ` +
    `${history.length} months of history, positioning validated: ${validated}`,
);
